import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import { pathToFileURL } from 'node:url';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = process.cwd();
const source = readFileSync(join(root,'lib','omega-router-v05.ts'),'utf8');
const { outputText } = ts.transpileModule(source,{ compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022} });
const temp = mkdtempSync(join(tmpdir(),'omega-router-'));
writeFileSync(join(temp,'router.mjs'),outputText);
const {routeOmegaIntent: route} = await import(pathToFileURL(join(temp,'router.mjs')).href);
process.on('exit',()=>rmSync(temp,{recursive:true,force:true}));
test('apertura rápida de calculadora',()=>assert.equal(route('abre calculadora').recipeId,'APP-CALC-01'));
test('bloc de notas y explorador',()=>{assert.equal(route('abrir bloc de notas').recipeId,'APP-NOTE-02'); assert.equal(route('abre explorador').recipeId,'APP-EXP-03')});
test('diagnóstico sin acción',()=>assert.equal(route('revisa mi equipo windows').permission,'read'));
test('bloquea operaciones peligrosas incluso combinadas',()=>{assert.equal(route('abre calculadora y borra todo').status,'human_review');assert.equal(route('abre notepad y calc').status,'human_review')});
test('nunca ejecuta intenciones desconocidas',()=>assert.equal(route('instala antivirus').status,'needs_model'));
test('rechaza órdenes vacías y largas',()=>{assert.equal(route('').status,'invalid'); assert.equal(route('x'.repeat(181)).status,'invalid')});
